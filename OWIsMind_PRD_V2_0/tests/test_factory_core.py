class TestPipelineDryRun(unittest.TestCase):
    def test_full_dry_run_plans_without_touching_dss(self):
        spec = DomainSpec(domain="satisfaction", base_dataset="CX_Surveys",
                          label_fr="Expert satisfaction", label_en="Satisfaction expert",
                          source={"connection": "SQL_owi", "schema": "public",
                                  "table": "cx_surveys"})
        ctx = FactoryContext(project=_FakeProject(), dry_run=True)
        pipeline.create_domain(ctx, spec)
        statuses = {a["status"] for a in ctx.actions}
        self.assertFalse(ctx.has_failures(), ctx.actions)
        self.assertIn(PLANNED, statuses)
        self.assertIn(MANUAL, statuses)
        steps = [a["step"] for a in ctx.actions]
        for expected in ("source_dataset", "zone", "scenario", "semantic_model",
                         "capability", "smoke_checklist", "first_build"):
            self.assertIn(expected, steps, "missing step %s in %s" % (expected, steps))
        # The gated steps degrade to manual/planned, never fail, in dry-run.
        report = ctx.report_markdown()
        self.assertIn("DRY RUN", report)


